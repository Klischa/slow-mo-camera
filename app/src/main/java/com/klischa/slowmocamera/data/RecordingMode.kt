package com.klischa.slowmocamera.data

/**
 * Режимы сохранения высокоскоростного видео.
 */
enum class RecordingMode(val displayName: String, val description: String) {
    /**
     * High-Frame-Rate (HFR):
     * Захват с высокой частотой (например 120 или 240 fps), но контейнер сохраняется
     * со стандартной частотой 30 fps. При обычном воспроизведении видео СРАЗУ замедлено в 4x / 8x раз.
     */
    HFR(
        displayName = "HFR Slow-Mo (30fps)",
        description = "Захват на высокой частоте (120/240 fps), сохранение 30 fps контейнера. Замедление 'из коробки'."
    ),

    /**
     * High-Speed Recording (HSR):
     * Захват и сохранение в файл происходят с полной высокой частотой (120 или 240 fps).
     * Плеер воспроизводит видео плавно на высокой частоте или замедляет по требованию.
     */
    HSR(
        displayName = "HSR High-FPS",
        description = "Захват и сохранение с полной частотой кадров (120/240 fps). Плеер может плавно менять скорость."
    )
}
